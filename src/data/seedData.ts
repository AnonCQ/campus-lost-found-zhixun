/**
 * P0-2: Cached Image Embeddings (6 unique sha256 + modelVersion documents for the 12 items!)
 * Derived deterministically from (sha256, modelVersion) ONLY so seed and publish always share the exact same doc.
 * Populated with real 3072D L2-normalized image embeddings from gemini-embedding-2.
 */
export function buildSeedEmbeddings(realVectorsBySha: Map<string, number[]>): ImageEmbedding[] {
  const uniqueBySha = new Map<string, LostFoundItem>();
  for (const item of SEED_ITEMS) {
    if (item.imageSha256 && !uniqueBySha.has(item.imageSha256)) {
      uniqueBySha.set(item.imageSha256, item);
    }
  }
  const embeddings: ImageEmbedding[] = [];
  for (const [sha256, item] of uniqueBySha.entries()) {
    const id = getDeterministicEmbeddingId(sha256, EMBEDDING_MODEL_VERSION);
    const vector = realVectorsBySha.get(sha256);
    if (!vector || vector.length === 0) {
      throw new Error(`Missing real image embedding vector for seed sha256: ${sha256}`);
    }
    embeddings.push({
      id,
      sha256,
      modelVersion: EMBEDDING_MODEL_VERSION,
      dimension: vector.length,
      vector,
      itemId: item.id,
      visualSummary: `${item.campusCategory} · ${item.color || ''} · ${item.rawModelClass || ''}`,
      createdAt: item.createdAt,
    });
  }
  return embeddings;
}

